/**
 * Downloads the website's square 1x1 SVG flags into lib/brand/siteFlags.ts.
 * Node 20+, plain fetch. No packages.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const CODES = [
  "au",
  "ca",
  "dk",
  "fi",
  "fr",
  "de",
  "is",
  "ie",
  "nl",
  "nz",
  "no",
  "pt",
  "sg",
  "es",
  "se",
  "ch",
  "ae",
  "gb",
  "us",
];

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "lib", "brand", "siteFlags.ts");

async function fetchFlag(code) {
  const url = `https://www.globalsponsorhub.com/flags/1x1/${code}.svg`;
  const res = await fetch(url);
  if (res.status !== 200) {
    throw new Error(`${code}: expected 200, got ${res.status} (${url})`);
  }
  const type = (res.headers.get("content-type") || "").toLowerCase();
  if (!type.includes("image/svg+xml") && !type.includes("svg")) {
    throw new Error(`${code}: expected image/svg+xml, got ${type}`);
  }
  const text = (await res.text()).trim();
  if (!text.startsWith("<svg")) {
    throw new Error(`${code}: response does not start with <svg`);
  }
  console.log(`${code}: ${text.length} chars`);
  return text;
}

function escapeTemplate(svg) {
  return svg.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$/g, "\\$");
}

const entries = {};
for (const code of CODES) {
  entries[code] = await fetchFlag(code);
}

mkdirSync(dirname(outPath), { recursive: true });
const body = `/** Square website flags (1x1 SVG). Generated by scripts/fetch-site-flags.mjs — do not edit by hand. */
export const SITE_FLAGS: Record<string, string> = {
${CODES.map((code) => `  ${JSON.stringify(code)}: \`${escapeTemplate(entries[code])}\`,`).join("\n")}
};
`;
writeFileSync(outPath, body, "utf8");
console.log(`Wrote ${CODES.length} flags to lib/brand/siteFlags.ts`);
