/**
 * Downloads the Global Sponsor Hub logo mark path from the live website
 * and writes lib/brand/gshMarkPath.ts for GshMark to render.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "lib", "brand", "gshMarkPath.ts");
const URL = "https://www.globalsponsorhub.com/";
const EXPECTED_VIEWBOX = "0 0 1254 1254";
const PATH_START = "M130.00 592.53";
const PATH_END = "Z";

const html = await fetch(URL).then(async (res) => {
  if (!res.ok) throw new Error(`Failed to fetch ${URL}: ${res.status}`);
  return res.text();
});

const svgMatch = html.match(
  /<svg[^>]*class="[^"]*gsh-home-hero-mark[^"]*"[^>]*>([\s\S]*?)<\/svg>/i,
);
if (!svgMatch) {
  throw new Error('Could not find <svg class="gsh-home-hero-mark"> on the homepage.');
}

const svgTag = html.slice(html.indexOf(svgMatch[0]), html.indexOf(svgMatch[0]) + svgMatch[0].length);
const viewBoxMatch = svgTag.match(/viewBox="([^"]+)"/i);
const pathMatch = svgTag.match(/<path[^>]*\sd="([^"]+)"/i);

if (!viewBoxMatch) throw new Error("SVG mark is missing a viewBox.");
if (!pathMatch) throw new Error("SVG mark is missing a path d attribute.");

const viewBox = viewBoxMatch[1].trim();
const d = pathMatch[1].trim();

if (viewBox !== EXPECTED_VIEWBOX) {
  throw new Error(`Unexpected viewBox "${viewBox}" (expected "${EXPECTED_VIEWBOX}").`);
}
if (!d.startsWith(PATH_START)) {
  throw new Error(`Unexpected path start "${d.slice(0, 24)}…" (expected "${PATH_START}").`);
}
if (!d.endsWith(PATH_END)) {
  throw new Error(`Unexpected path end (expected to end with "${PATH_END}").`);
}

const contents = `/** Auto-generated by scripts/fetch-gsh-mark.mjs — do not edit by hand. */
export const GSH_MARK_VIEWBOX = ${JSON.stringify(viewBox)} as const;
export const GSH_MARK_PATH = ${JSON.stringify(d)} as const;
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, contents, "utf8");
console.log(`Wrote ${OUT}`);
console.log(`viewBox=${viewBox}`);
console.log(`path length=${d.length}`);
